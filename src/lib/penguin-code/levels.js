export function getPenguinLevel(level) {
  const index = Math.max(0, Math.min(PENGUIN_LEVEL_COUNT - 1, Number(level) - 1 || 0));
  return PENGUIN_LEVELS[index];
}

export function getPenguinWorld(world) {
  const index = Math.max(0, Math.min(PENGUIN_WORLD_COUNT - 1, Number(world) - 1 || 0));
  return PENGUIN_WORLDS[index];
}

export function worldLevels(world) {
  const { id } = getPenguinWorld(world);
  return PENGUIN_LEVELS.filter((level) => level.world === id);
}
